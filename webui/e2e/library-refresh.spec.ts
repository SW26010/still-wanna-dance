  let inventory={totalSongs:2,coveredSongs:1,coverageKnown:true,updated:'2026-10-16T00:00:00Z',scanning:false},reads=0;
  await page.route('**/api/inventory',route=>{reads++;return route.fulfill({json:inventory});});
