import {test,expect} from '@playwright/test';
import {mockAPI,choosePath} from './api';

for(const width of [320,1280])test(`import space preview keeps layout and ignores old selections at ${width}px`,async({page},info)=>{
  const api=await mockAPI(page);
  api.state.settings.videoDir='E:\\Not active';
  let release!:()=>void,finished!:()=>void;
  const held=new Promise<void>(resolve=>release=resolve),done=new Promise<void>(resolve=>finished=resolve);
  await page.route('**/api/import/space?*',async route=>{
    const source=new URL(route.request().url()).searchParams.get('source');
    if(source==='D:\\Slow')await held;
    await route.fulfill({json:{mode:source==='E:\\Source'?'cross-volume':source==='D:\\Missing'?'unknown':'same-volume',videoDir:api.state.activeSettings.videoDir}});
    if(source==='D:\\Slow')finished();
  });
  await page.setViewportSize({width,height:1000});
  await page.goto('/#video-import');
  const panel=page.locator('#video-import'),start=panel.getByRole('button',{name:'扫描并导入',exact:true});
  const position=()=>start.evaluate(el=>el.getBoundingClientRect().top-el.closest('#video-import')!.getBoundingClientRect().top);
  await expect(panel.getByText('选择来源后显示空间预估',{exact:true})).toBeVisible();
  const initial=await position();
  await choosePath(page,'外部目录','D:\\Source');
  const shared=panel.getByText('预计不额外占用视频空间',{exact:true});
  await expect(shared).toBeVisible();
  const labelBox=(await panel.getByText('外部目录',{exact:true}).boundingBox())!,hintBox=(await shared.boundingBox())!;
  expect(hintBox.x).toBeGreaterThanOrEqual(labelBox.x+labelBox.width);
  expect(hintBox.y).toBeLessThan(labelBox.y+labelBox.height);
  await expect(panel.getByRole('textbox',{name:'外部目录',exact:true})).toBeVisible();
  expect(await position()).toBe(initial);
  await shared.hover();
  await expect(page.getByRole('tooltip')).toContainText('硬链接共享原视频内容');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await shared.click();
  expect(api.calls.some(c=>c.path==='path/select')).toBe(false);
  await page.mouse.move(0,0);
  await panel.getByRole('textbox',{name:'外部目录',exact:true}).focus();
  await page.keyboard.press('Shift+Tab');
  await expect(shared).toBeFocused();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await page.keyboard.press('Escape');
  await panel.screenshot({path:info.outputPath('same-volume.png')});
  await choosePath(page,'外部目录','D:\\Slow');
  await expect(panel.getByText('正在判断空间占用…',{exact:true})).toBeVisible();
  expect(await position()).toBe(initial);
  await choosePath(page,'外部目录','E:\\Source');
  const copied=panel.getByText('预计需要额外空间',{exact:true});
  await expect(copied).toBeVisible();
  release();await done;
  await expect(copied).toBeVisible();
  expect(await position()).toBe(initial);
  await choosePath(page,'外部目录','D:\\Missing');
  await expect(panel.getByText('空间占用待确认',{exact:true})).toBeVisible();
  expect(await position()).toBe(initial);
  await panel.getByRole('button',{name:'外部目录：恢复默认'}).click();
  await expect(panel.getByText('选择来源后显示空间预估',{exact:true})).toBeVisible();
  expect(await position()).toBe(initial);
  expect(api.calls.some(c=>c.path==='import/start')).toBe(false);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

test('import space lookup failure leaves import available and a restored batch uses its bound target',async({page})=>{
  const api=await mockAPI(page);
  api.state.import={id:42,present:true,paused:true,source:'D:\\Source',videoDir:'E:\\Original target'};
  await page.route('**/api/import/space?*',route=>route.fulfill({status:503,body:'unavailable'}));
  await page.goto('/#video-import');
  const panel=page.locator('#video-import');
  await expect(panel.getByText('空间占用待确认',{exact:true})).toBeVisible();
  await expect(panel.getByRole('button',{name:'继续导入',exact:true})).toBeEnabled();
  await page.unroute('**/api/import/space?*');
  await page.route('**/api/import/space?*',route=>route.fulfill({json:{mode:'cross-volume',videoDir:'E:\\Original target'}}));
  await page.reload();
  await expect(panel.getByText('预计需要额外空间',{exact:true})).toBeVisible();
});
