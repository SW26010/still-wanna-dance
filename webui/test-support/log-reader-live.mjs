  const expand=page.getByRole('button',{name:'展开日志表格',exact:true});
  await expand.click();
  const dialog=page.getByRole('dialog',{name:'程序日志表格',exact:true});
  await expect(dialog).toBeVisible();await expect(dialog.locator('tbody tr')).toHaveCount(3);
  await expect(dialog.getByRole('navigation',{name:'日志分页',exact:true})).toHaveCount(0);
  await expect(dialog.getByRole('heading')).toHaveCount(0);await expect(dialog.getByRole('status')).toHaveCount(0);
  await expect.poll(async()=>Math.round((await dialog.boundingBox()).width)).toBe(1280);
  await expect.poll(async()=>Math.round((await dialog.boundingBox()).height)).toBe(950);
  expect(await dialog.getByRole('region',{name:'程序日志表格',exact:true}).boundingBox()).toEqual({x:0,y:0,width:1280,height:950});
  await page.screenshot({animations:'disabled',path:join(output,'expanded-logs-wide-light.png')});
  await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);await expect(expand).toBeFocused();
  const event=page.getByRole('searchbox',{name:'事件关键词',exact:true});
  await event.fill('RROR');await expect(rows).toHaveCount(3);
  await page.getByLabel('开始时间',{exact:true}).fill('2026-11-02T09:30:01');await page.getByLabel('结束时间',{exact:true}).fill('2026-11-02T11:30:01');
  await page.getByRole('combobox',{name:'级别',exact:true}).selectOption('ERROR');
  const queryResponse=page.waitForResponse(response=>response.url().includes('/api/logs?')&&new URL(response.url()).searchParams.get('event')==='RROR');
  await event.press('Enter');const response=await queryResponse;
  expect(response.ok()).toBe(true);const result=await response.json();
  expect(result.entries.map(entry=>entry.message)).toEqual(['fixture_error']);expect(result).not.toHaveProperty('events');expect(result.files).toEqual(['app.log.1','app.log']);
  await expect(rows).toHaveCount(1);
  const contentCell=rows.first().getByRole('cell').nth(3);
  await expect(contentCell).toContainText('9007199254740993');await expect(contentCell).toContainText('<script>literal text</script>');
  await expect(contentCell).toContainText('long-path/'.repeat(20));expect(await contentCell.textContent()).toContain('two  spaces');
  await expect(contentCell.locator('strong')).toHaveText(result.entries[0].fields.map(field=>field.key));
  await expect(contentCell).toContainText('not_a_key=inside value');
  const region=page.getByRole('region',{name:'程序日志表格',exact:true});
  expect(await region.evaluate(element=>element.scrollWidth>element.clientWidth)).toBe(true);
  await region.focus();await page.keyboard.press('ArrowRight');await expect.poll(()=>region.evaluate(element=>element.scrollLeft)).toBeGreaterThan(0);
  await region.evaluate(element=>element.scrollLeft=element.scrollWidth);
  await page.screenshot({animations:'disabled',path:join(output,'compact-logs-content-end.png')});
  const saving=page.waitForEvent('download');await page.getByRole('button',{name:'导出日志',exact:true}).click();const download=await saving;
  expect(download.suggestedFilename()).toBe('swd-logs.txt');expect(await download.failure()).toBeNull();
  const content=await readFile(await download.path(),'utf8');expect(content).toContain('9007199254740993');expect(content).toContain('[ERROR] fixture_error');expect(content).not.toContain('fixture_info');
  await download.saveAs(join(output,'filtered-logs.txt'));
  await page.setViewportSize({width:390,height:844});await page.emulateMedia({colorScheme:'dark'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await region.evaluate(element=>element.scrollLeft=0);
  await page.screenshot({animations:'disabled',path:join(output,'compact-logs-narrow-dark.png'),fullPage:true});
  await expand.click();await expect(dialog.locator('tbody tr')).toHaveCount(1);
  await expect.poll(async()=>Math.round((await dialog.boundingBox()).width)).toBe(390);
  await expect.poll(async()=>Math.round((await dialog.boundingBox()).height)).toBe(844);
  expect(await dialog.getByRole('region',{name:'程序日志表格',exact:true}).boundingBox()).toEqual({x:0,y:0,width:390,height:844});
  await page.screenshot({animations:'disabled',path:join(output,'expanded-logs-narrow-dark.png')});
  await dialog.getByRole('button',{name:'退出日志展开视图',exact:true}).click();await expect(expand).toBeFocused();
  await page.getByRole('button',{name:'重置筛选',exact:true}).click();await expect(rows).toHaveCount(3);await expect(event).toHaveValue('');
  await page.getByRole('combobox',{name:'级别',exact:true}).selectOption('WARN');await page.getByRole('button',{name:'查询日志',exact:true}).click();await expect(rows).toHaveCount(1);await expect(rows).toContainText('fixture_warning');
  await event.fill('INFO');await event.press('Enter');
  await expect(page.getByText('当前筛选条件下没有日志。',{exact:true})).toBeVisible();await expect(event).toHaveValue('INFO');
  await event.fill('');await event.press('Enter');await expect(rows).toHaveCount(1);await expect(rows).toContainText('fixture_warning');
