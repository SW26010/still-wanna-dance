import {test,expect} from '@playwright/test';
import {mockAPI} from './api';

for(const width of [1280,390,320])test(`coverage keeps a compact layout and explains uncertain data at ${width}px`,async({page},info)=>{
  const api=await mockAPI(page);
  let known=true,unresolved=0;
  await page.route('**/api/inventory',r=>r.fulfill({json:{coverageKnown:known,totalSongs:known?3:0,coveredSongs:known?1:0,unresolvedSongs:known?unresolved:0,updated:'2026-10-29T00:00:00Z',catalogRevision:known?'20261029000000':''}}));
  api.state.batch={scanOnly:true,total:3,checked:3,hits:1,missing:0,unresolved:2,phase:'本地检查完成'};
  await page.setViewportSize({width,height:900});
  await page.emulateMedia({colorScheme:width===390?'dark':'light',forcedColors:width===320?'active':'none',reducedMotion:'reduce'});
  await page.goto('/#/library');
  const coverage=page.getByRole('group',{name:'曲库覆盖率',exact:true});
  const summary=page.getByRole('region',{name:'曲库概览'});
  const warning=coverage.getByRole('button',{name:'覆盖率说明',exact:true});
  const tooltip=page.getByRole('tooltip');
  const layout=()=>page.evaluate(()=>{
    const summary=document.querySelector('#overview')!.getBoundingClientRect();
    const table=document.querySelector('table[aria-label="曲库歌曲"]')!.getBoundingClientRect();
    const budget=document.querySelector('#overview a[href="#storage-settings"]')!.getBoundingClientRect();
    return {height:summary.height,tableY:table.y+scrollY,budgetX:budget.x,budgetY:budget.y+scrollY};
  });
  await expect(coverage).toContainText('33.3%');
  await expect(warning).toHaveCount(0);
  await expect(coverage).not.toContainText('已覆盖');
  await expect(page.getByRole('table',{name:'曲库歌曲'}).locator('tbody tr')).toHaveCount(2);
  const before=await layout();
  await summary.screenshot({path:info.outputPath('normal.png'),animations:'disabled'});
  await coverage.getByText('曲库覆盖率',{exact:true}).hover();
  await expect(tooltip).toContainText('已覆盖 1 / 当前清单 3 首');
  await expect(tooltip).toContainText('统计清单版本：20261029000000');
  await page.keyboard.press('Escape');await page.mouse.move(0,0);

  unresolved=2;await page.reload();
  await expect(warning).toBeVisible();
  await expect(coverage).toContainText('33.3%');
  await expect(coverage).not.toContainText('资源待识别');
  await expect(page.locator('#batch')).toContainText('缺失 0 · 资源待识别 2');
  expect(await layout()).toEqual(before);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await summary.screenshot({path:info.outputPath('warning.png'),animations:'disabled'});
  await warning.hover();
  await expect(tooltip).toContainText('资源待识别 2 首');
  await expect(tooltip).toContainText('已计入当前清单总数，暂未计为已覆盖');
  await expect(warning).toHaveAccessibleDescription(/资源待识别 2 首/);
  const bounds=(await tooltip.boundingBox())!,overview=(await summary.boundingBox())!;
  expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(width);
  const left=Math.min(bounds.x,overview.x),top=Math.min(bounds.y,overview.y);
  await page.screenshot({path:info.outputPath('warning-tooltip.png'),animations:'disabled',clip:{x:left,y:top,width:Math.max(bounds.x+bounds.width,overview.x+overview.width)-left,height:Math.max(bounds.y+bounds.height,overview.y+overview.height)-top}});
  await page.keyboard.press('Escape');await expect(tooltip).toHaveCount(0);await page.mouse.move(0,0);
  await coverage.getByRole('button',{name:'更新曲库',exact:true}).focus();await page.keyboard.press('Tab');
  await expect(warning).toBeFocused();await expect(tooltip).toContainText('资源待识别 2 首');
  await page.keyboard.press('Escape');await expect(tooltip).toHaveCount(0);await expect(warning).toBeFocused();

  unresolved=0;await page.reload();
  await expect(coverage).toContainText('33.3%');await expect(warning).toHaveCount(0);
  expect(await layout()).toEqual(before);
  known=false;await page.reload();
  await expect(coverage).toContainText('—');
  await expect(coverage).not.toContainText('%');
  await expect(coverage).not.toContainText('已覆盖');
  await warning.hover();await expect(tooltip).toContainText('尚无有效的完整清单');
  await expect(tooltip).toContainText('请更新曲库');
  expect(api.calls.some(c=>c.path==='inventory/scan')).toBe(false);
});

test('failed coverage check hides the old percentage and explains the file error',async({page})=>{
  await mockAPI(page);
  const error='无法读取视频目录：磁盘不可用';
  await page.route('**/api/inventory',r=>r.fulfill({json:{coverageKnown:false,totalSongs:3,coveredSongs:1,updated:'2026-10-29T00:00:00Z',catalogRevision:'20261028000000',catalog:{revision:'20261029000000'},error}}));
  await page.goto('/#/library');
  const coverage=page.getByRole('group',{name:'曲库覆盖率',exact:true});
  await expect(coverage).toContainText('—');
  await expect(coverage).not.toContainText('%');
  const warning=coverage.getByRole('button',{name:'覆盖率说明',exact:true});
  await warning.focus();
  await expect(page.getByRole('tooltip')).toContainText(error);
  await expect(page.getByRole('tooltip')).not.toContainText('尚无有效的完整清单');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
});

for(const width of [1280,390,320])test(`catalog initialization keeps positions and explains progress in the tooltip at ${width}px`,async({page},info)=>{
  const api=await mockAPI(page);
  await page.setViewportSize({width,height:900});
  await page.emulateMedia({colorScheme:width===390?'dark':'light',forcedColors:width===320?'active':'none',reducedMotion:'no-preference'});
  const complete={coverageKnown:true,totalSongs:3,coveredSongs:2,updated:'2026-10-29T01:00:06Z',catalogRevision:'20261029000000',catalog:{revision:'20261029000000'}};
  let inventory:Record<string,unknown>=complete;
  await page.route('**/api/inventory',r=>r.fulfill({json:inventory}));
  await page.goto('/#/library');
  const coverage=page.getByRole('group',{name:'曲库覆盖率',exact:true});
  const summary=page.getByRole('region',{name:'曲库概览'});
  const update=coverage.getByRole('button',{name:'更新曲库',exact:true}),icon=update.locator('.refresh-icon');
  const warning=coverage.getByRole('button',{name:'覆盖率说明',exact:true}),tooltip=page.getByRole('tooltip');
  const layout=()=>page.evaluate(()=>{
    const position=(selector:string)=>{const r=document.querySelector(selector)!.getBoundingClientRect();return {x:r.x,y:r.y+scrollY};};
    return {height:document.querySelector('#overview')!.getBoundingClientRect().height,coverage:position('#overview [aria-label="曲库覆盖率"]'),budget:position('#overview a[href="#storage-settings"]'),actions:position('#overview .library-actions'),table:position('table[aria-label="曲库歌曲"]')};
  });
  await expect(coverage).toContainText('66.7%');
  const before=await layout();
  inventory={coverageKnown:false,totalSongs:0,coveredSongs:0,catalog:{}};
  api.state.upstreamMonitor={catalogInitializing:true,checking:true,results:[]};
  await page.reload();
  await expect(coverage).toContainText('—');
  await expect(coverage).not.toContainText('正在获取');
  await expect(update).toHaveAttribute('aria-busy','true');
  await expect(update).toBeDisabled();
  await expect(icon).toHaveCSS('animation-name','refresh-spin');
  await expect(icon).toHaveCSS('animation-duration','1.5s');
  expect(await layout()).toEqual(before);
  await summary.screenshot({path:info.outputPath('initializing.png'),animations:'disabled'});
  await warning.hover();
  await expect(tooltip).toContainText('正在获取完整歌曲清单');
  await expect(warning).toHaveAccessibleDescription(/正在获取完整歌曲清单/);
  const tip=(await tooltip.boundingBox())!,box=(await summary.boundingBox())!;
  expect(tip.x).toBeGreaterThanOrEqual(0);expect(tip.x+tip.width).toBeLessThanOrEqual(width);
  const left=Math.min(tip.x,box.x),top=Math.min(tip.y,box.y);
  await page.screenshot({path:info.outputPath('initializing-tooltip.png'),animations:'disabled',clip:{x:left,y:top,width:Math.max(tip.x+tip.width,box.x+box.width)-left,height:Math.max(tip.y+tip.height,box.y+box.height)-top}});
  await page.keyboard.press('Escape');await page.mouse.move(0,0);
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(icon).toHaveCSS('animation-name','none');
  await expect(update).toHaveAttribute('aria-busy','true');
  await page.emulateMedia({reducedMotion:'no-preference'});
  api.state.upstreamMonitor={catalogInitializing:true,checking:false,finished:'2026-10-29T01:00:00Z',nextCheck:'2026-10-29T01:00:05Z',results:[{operation:'catalog',route:'api',mode:'direct',entry:'https://api.udon.dance/Api/Songs/list',state:'unavailable',reason:'timeout'}]};
  await expect(update).toHaveAttribute('aria-busy','false',{timeout:10000});
  await expect(update).toBeEnabled();
  await expect(icon).toHaveCSS('animation-name','none');
  await expect(coverage).toContainText('—');
  await expect(coverage).not.toContainText('等待重试');
  await warning.focus();
  await expect(tooltip).toContainText('请求超时');
  await expect(tooltip).toContainText('程序会自动重试');
  await expect(tooltip).toContainText('下次尝试');
  await page.keyboard.press('Escape');
  await expect(tooltip).toHaveCount(0);
  expect(await layout()).toEqual(before);
  await summary.screenshot({path:info.outputPath('retry.png'),animations:'disabled'});
  inventory=complete;
  api.state.upstreamMonitor={catalogInitializing:false,checking:false,finished:'2026-10-29T01:00:06Z',results:[]};
  await expect(coverage).toContainText('66.7%',{timeout:10000});
  await expect(warning).toHaveCount(0);
  expect(await layout()).toEqual(before);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(api.calls.some(c=>c.path==='inventory/scan')).toBe(false);
  await summary.screenshot({path:info.outputPath('initialized.png'),animations:'disabled'});
});

