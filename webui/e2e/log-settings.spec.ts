import {test,expect} from '@playwright/test';
import {mockAPI} from './api';
import {navigateSettings} from './navigation';
import {saveSettings} from './settings-actions';

test('program log settings share a row and stage changes until restart',async({page},testInfo)=>{
  const api=await mockAPI(page);
  const configuredBudget=20*1048576+1;
  api.state.settings.logBudgetBytes=api.state.activeSettings.logBudgetBytes=configuredBudget;
  await page.setViewportSize({width:1280,height:900});
  await page.goto('/#/settings');
  const level=page.getByRole('combobox',{name:'程序日志级别',exact:true});
  const budget=page.getByRole('spinbutton',{name:'程序日志大小上限（MiB）',exact:true});
  const save=page.getByRole('button',{name:'保存设置',exact:true});
  await expect(level).toHaveValue('info');
  await expect(budget).toHaveValue('20');
  const levelBox=(await level.boundingBox())!,budgetBox=(await budget.boundingBox())!;
  expect(budgetBox.x).toBeGreaterThanOrEqual(levelBox.x+levelBox.width);
  expect(budgetBox.y).toBeCloseTo(levelBox.y,0);
  expect(await level.locator('option').evaluateAll(options=>options.map(option=>option.getAttribute('value')))).toEqual(['off','error','warn','info','debug']);
  await level.selectOption('debug');
  await navigateSettings(page,'网络');await navigateSettings(page,'常规');
  await expect(level).toHaveValue('debug');
  await page.getByRole('button',{name:'放弃更改',exact:true}).click();
  await expect(level).toHaveValue('info');
  await level.selectOption('off');await save.click();
  await expect(save).toBeDisabled();
  await expect(page.getByRole('button',{name:'重启并应用',exact:true})).toBeEnabled();
  expect(api.state.settings.logLevel).toBe('off');
  expect(api.state.activeSettings.logLevel).toBe('info');
  expect(api.state.settings.logBudgetBytes).toBe(configuredBudget);
  await page.reload();await expect(level).toHaveValue('off');
  await budget.fill('0');await save.click();
  await expect(budget).toHaveAttribute('aria-invalid','true');
  expect(api.state.settings.logBudgetBytes).toBe(configuredBudget);
  await budget.fill('');
  await expect(budget).toHaveAttribute('placeholder','20');
  await saveSettings(page,'待重启');
  expect(api.state.settings.logBudgetBytes).toBe(20*1048576);
  await budget.fill('64');
  await saveSettings(page,'待重启');
  expect(api.state.settings.logBudgetBytes).toBe(64*1048576);
  expect(api.state.activeSettings.logBudgetBytes).toBe(configuredBudget);
  await page.reload();await expect(budget).toHaveValue('64');
  await navigateSettings(page,'下载与缓存');
  await page.getByRole('spinbutton',{name:'提前准备时间（秒）',exact:true}).fill('600');
  await saveSettings(page,'待重启');
  expect(api.state.settings.logLevel).toBe('off');
  await navigateSettings(page,'常规');
  await expect(budget).toHaveValue('64');
  await page.setViewportSize({width:390,height:844});
  await level.scrollIntoViewIfNeeded();
  expect((await budget.boundingBox())!.y).toBeGreaterThan((await level.boundingBox())!.y);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('log-settings-light.png')});
  await page.getByLabel('主题',{exact:true}).selectOption('dark');
  await expect(page.locator('#root > .app-provider')).toHaveAttribute('data-theme','dark');
  await level.scrollIntoViewIfNeeded();
  await page.screenshot({path:testInfo.outputPath('log-settings-dark.png')});
  expect(api.calls.some(c=>c.path.startsWith('activation/')||c.path.startsWith('hosts/'))).toBe(false);
});
