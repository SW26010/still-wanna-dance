  await writeFile(join(output,'browser-result.json'),JSON.stringify({passed:true,files:result.files,keyword:'RROR',filtered:result.entries.map(entry=>entry.message),errors},null,2));
  console.log('Real Console log reader: case-insensitive event keyword search, Enter submission, no enumeration, compact Fluent table, text-only download, precise fields and narrow layout passed.');
