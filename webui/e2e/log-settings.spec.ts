import {test,expect} from '@playwright/test';
import {mockAPI} from './api';
import {navigateSettings} from './navigation';

test('log level drafts, save and reload keep the active level until restart',async({page},testInfo)=>{
  const api=await mockAPI(page);
  await page.goto('/#/settings');
  const level=page.getByRole('combobox',{name:'程序日志级别',exact:true});
  const save=page.getByRole('button',{name:'保存设置',exact:true});
  await expect(level).toHaveValue('info');
  await expect(level).toHaveAccessibleDescription(/保存后重启生效/);
  await expect(level).toHaveAccessibleDescription(/关闭不会删除已有日志/);
  expect(await level.locator('option').evaluateAll(options=>options.map(option=>option.getAttribute('value')))).toEqual(['off','error','warn','info','debug']);
  await level.selectOption('debug');
  await navigateSettings(page,'网络');await navigateSettings(page,'常规');
  await expect(level).toHaveValue('debug');
  await page.getByRole('button',{name:'放弃更改',exact:true}).click();
  await expect(level).toHaveValue('info');
  await level.selectOption('off');await save.click();
  await expect(save).toBeDisabled();
  await expect(page.getByRole('button',{name:'重启并应用',exact:true})).toBeEnabled();
  expect(api.state.settings.logLevel).toBe('off');
  expect(api.state.activeSettings.logLevel).toBe('info');
  await page.reload();await expect(level).toHaveValue('off');
  await navigateSettings(page,'预加载与下载');
  await page.getByRole('spinbutton',{name:'提前准备时间（秒）',exact:true}).fill('600');
  await save.click();await expect(save).toBeDisabled();
  expect(api.state.settings.logLevel).toBe('off');
  await navigateSettings(page,'常规');
  await page.setViewportSize({width:390,height:844});
  await level.scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('log-settings-light.png')});
  await page.getByLabel('主题',{exact:true}).selectOption('dark');
  await expect(page.locator('#root > .app-provider')).toHaveAttribute('data-theme','dark');
  await level.scrollIntoViewIfNeeded();
  await page.screenshot({path:testInfo.outputPath('log-settings-dark.png')});
  expect(api.calls.some(c=>c.path.startsWith('activation/')||c.path.startsWith('hosts/'))).toBe(false);
});
