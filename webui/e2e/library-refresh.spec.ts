for(const width of [1280,390,320])for(const kind of ['local','catalog'] as const)test(`${kind} refresh keeps the summary and table in place at ${width}px`,async({page},info)=>{
  const api=await mockAPI(page);
  const inventory={totalSongs:2,coveredSongs:1,coverageKnown:true,updated:'2026-10-16T00:00:00Z',scanning:false};
  let holdLocal=false,localReads=0,inventoryReads=0,scans=0;
  let releaseLocal=()=>{};
  const localResponse=new Promise<void>(resolve=>{releaseLocal=resolve;});
  await page.route('**/api/library?*',async route=>{localReads++;if(holdLocal)await localResponse;await route.fallback();});
  await page.route('**/api/inventory',route=>{inventoryReads++;return route.fulfill({json:inventory});});
  await page.route('**/api/inventory/scan',route=>{scans++;inventory.scanning=true;return route.fulfill({json:{ok:true}});});
  await page.clock.install();await page.setViewportSize({width,height:900});
  await page.emulateMedia({colorScheme:width===390?'dark':'light',reducedMotion:'no-preference'});
  await page.goto('/#/library');
  const button=page.getByRole('button',{name:kind==='local'?'检查本地视频':'更新曲库',exact:true});
  await expect(button).toBeEnabled();
  await expect(page.getByRole('table',{name:'曲库歌曲'}).locator('tbody tr')).toHaveCount(2);
  const icon=button.locator('svg');
  await expect(icon).toBeVisible();
  expect(await icon.evaluate(el=>el.getAnimations().length)).toBe(0);
  const lastTime=await checkTime(page,kind==='local'?'检查本地视频':'更新曲库');
  const layout=async()=>page.evaluate(()=>{
    const summary=document.querySelector('#overview')!.getBoundingClientRect();
    const table=document.querySelector('table[aria-label="曲库歌曲"]')!.getBoundingClientRect();
    return {height:summary.height,tableY:table.y+scrollY};
  });
  const before=await layout(),buttonBefore=await button.boundingBox(),initialInventoryReads=inventoryReads;
  holdLocal=kind==='local';
  await button.focus();await button.press('Enter');
  await expect(button).toBeDisabled();
  if(kind==='local')await expect.poll(()=>localReads).toBe(2);
  else await expect.poll(()=>inventoryReads).toBeGreaterThan(initialInventoryReads);
  await page.clock.runFor(50);
  expect(await layout()).toEqual(before);
  const buttonDuring=await button.boundingBox();
  expect([buttonDuring!.width,buttonDuring!.height]).toEqual([buttonBefore!.width,buttonBefore!.height]);
  await expect(button).toHaveAttribute('aria-busy','true');await expect(button).toBeFocused();
  await expect(icon).toBeVisible();
  const rotation=await icon.evaluate(el=>getComputedStyle(el).transform);
  await expect.poll(()=>icon.evaluate(el=>getComputedStyle(el).transform)).not.toBe(rotation);
  await expect(button.locator('.fui-Spinner')).toHaveCount(0);
  await button.hover();
  await expect(page.getByRole('tooltip')).toContainText(kind==='local'?'检查本地视频':'更新曲库');
  await expect(page.getByRole('tooltip')).toContainText(lastTime);
  await expect(page.getByRole('tooltip')).not.toContainText(/正在|更新中|检查中/);
  await page.keyboard.press('Escape');await expect(page.getByRole('tooltip')).toHaveCount(0);
  await button.press('Enter');
  if(kind==='local')expect(localReads).toBe(2);else expect(scans).toBe(1);
  await page.getByRole('region',{name:'曲库概览'}).screenshot({path:info.outputPath('refreshing.png'),animations:'disabled'});
  await page.emulateMedia({reducedMotion:'reduce'});
  expect(await icon.evaluate(el=>el.getAnimations().length)).toBe(0);
  await expect(button).toHaveAttribute('aria-busy','true');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await expect.poll(()=>icon.evaluate(el=>el.getAnimations().length)).toBe(1);
  releaseLocal();inventory.scanning=false;
  await expectWithClock(page,()=>button.isEnabled()).toBe(true);await expect(button).toHaveAttribute('aria-busy','false');
  await expect(button.locator('.fui-Spinner')).toHaveCount(0);
  expect(await icon.evaluate(el=>el.getAnimations().length)).toBe(0);
  expect(await layout()).toEqual(before);
  expect(api.calls.some(c=>c.path==='batch/start')).toBe(false);
});
