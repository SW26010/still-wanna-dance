import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkWebUI, webuiManifest } from '../scripts/check-webui.mjs';
import { reviewWebuiBuild } from '../scripts/check-repository-artifacts.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const outdir = path.resolve(root, '../internal/console/assets/webui');
// Ship only the relevant series from the historical research, without making
// the browser load the full study or maintaining a second copy of its data.
const study = JSON.parse(fs.readFileSync(path.resolve(root, '../docs/research/cache-priority/study-data.json'), 'utf8'));
const budgets = study.byte_budgets_gib, coverage = study.byte_curves.exp_event_60;
const maxBudgetGiB = study.axis_limits.weekly_candidate_storage_gib_max;
const lastPoint = budgets.findIndex(value => value >= maxBudgetGiB);
if (!Number.isFinite(maxBudgetGiB) || lastPoint < 1 || budgets[0] !== 0 ||
    budgets.slice(0, lastPoint + 1).some((value, index) => !Number.isFinite(value) || index > 0 && value <= budgets[index - 1]) ||
    coverage.length <= lastPoint || coverage.slice(0, lastPoint + 1).some(value => !Number.isFinite(value) || value < 0 || value > 1)) {
  throw new Error('Invalid historical storage coverage curve');
}
const coverageReference = {maxBudgetGiB, budgets: budgets.slice(0, lastPoint + 1), values: coverage.slice(0, lastPoint + 1)};
const result = await build({ absWorkingDir: root, entryPoints: { app: 'src/main.tsx' }, outdir, bundle: true, minify: true,
  format: 'esm', target: ['es2022'], jsx: 'automatic', legalComments: 'eof', write: false, metafile: true,
  define: { 'process.env.NODE_ENV': '"production"', '__VIDEO_COVERAGE_REFERENCE__': JSON.stringify(coverageReference) } });
const check = process.argv.includes('--check');
// Include notices for precisely the packages linked into the browser bundle.
const packages = new Map();
const linked = new Set(Object.values(result.metafile.outputs).flatMap(output => Object.entries(output.inputs).filter(([, data]) => data.bytesInOutput > 0).map(([input]) => input)));
for (const input of [...linked].filter(p => p.includes('node_modules/'))) {
  let dir = path.dirname(path.resolve(root, input));
  while (!fs.existsSync(path.join(dir, 'package.json')) && dir !== path.dirname(dir)) dir = path.dirname(dir);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json')));
  if (packages.has(pkg.name)) continue;
  const license = fs.readdirSync(dir).find(n => /^licen[cs]e(?:\.md|\.txt)?$/i.test(n));
  const licenseFile = license ? path.join(dir, license) : pkg.name === '@fluentui/react-icons' && pkg.version === '2.0.344' ? path.resolve(root, '../docs/licenses/fluentui-system-icons-LICENSE') : null;
  if (!licenseFile) throw new Error(`Missing license: ${pkg.name}`);
  packages.set(pkg.name, `Package: ${pkg.name} ${pkg.version}\nLicense: ${pkg.license}\n\n${fs.readFileSync(licenseFile, 'utf8').replaceAll('\r\n', '\n').trim()}\n`);
}
result.outputFiles.push({ path: path.resolve(root, '../docs/licenses/WEBUI-NOTICES.txt'), contents: Buffer.from('Third-party packages embedded in the SWD Web UI\nGenerated by webui/build.mjs from bundled production inputs.\n\n' + [...packages].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([, text]) => text).join('\n----------------------------------------\n\n')) });
result.outputFiles.push({path:path.join(outdir,'webui-notices.txt'),contents:result.outputFiles.at(-1).contents});
for(const [input,name] of [['LICENSE','software-license.txt'],['THIRD-PARTY-NOTICES.txt','third-party-notices.txt'],['docs/licenses/ZASHBOARD-NOTICES.txt','zashboard-notices.txt']])result.outputFiles.push({path:path.join(outdir,name),contents:Buffer.from(fs.readFileSync(path.resolve(root,'..',input),'utf8').replaceAll('\r\n','\n'))});
for (const file of result.outputFiles) {
  if (check) {
    if (!fs.existsSync(file.path) || !fs.readFileSync(file.path).equals(file.contents)) throw new Error(`Stale bundle: ${file.path}. Run pnpm --dir webui build.`);
  } else { fs.mkdirSync(path.dirname(file.path), { recursive: true }); fs.writeFileSync(file.path, file.contents); }
}
if(check) checkWebUI(path.resolve(root,'..'));
else {
  const repo = path.resolve(root, '..');
  const manifest = webuiManifest(repo);
  fs.writeFileSync(path.join(root, 'build-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  const policy = JSON.parse(fs.readFileSync(path.join(repo, 'scripts/repository-artifacts-policy.json')));
  const app = result.outputFiles.find(file => file.path === path.join(outdir, 'app.js'));
  const review = reviewWebuiBuild(app.contents, policy, manifest);
  if (review) console.log('WebUI artifact registration needs review; the policy was not changed:\n' + JSON.stringify(review, null, 2));
}
console.log(`${check ? 'Verified' : 'Built'} embedded Fluent UI assets (${result.outputFiles.reduce((n, f) => n + f.contents.length, 0)} bytes).`);
