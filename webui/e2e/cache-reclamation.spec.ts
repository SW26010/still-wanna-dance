import {test, expect} from '@playwright/test';
import {mockAPI} from './api';
import {navigate,navigateSettings} from './navigation';
import {saveSettings} from './settings-actions';

test('reclamation strategy follows storage only in auto and survives save, discard and navigation', async ({page}, info) => {
  const api = await mockAPI(page);
  await page.goto('/#download-settings');
  const group = page.getByRole('radiogroup', {name:'激进的缓存回收策略', exact:true});
  const auto = group.getByRole('radio', {name:'自动（默认）', exact:true});
  const on = group.getByRole('radio', {name:'开启', exact:true});
  const off = group.getByRole('radio', {name:'关闭', exact:true});
  const save = page.getByRole('button', {name:'保存设置', exact:true});
  await expect(group.getByRole('radio')).toHaveCount(3);
  const label = page.getByText('激进的缓存回收策略',{exact:true});
  await label.hover();
  await expect(page.getByRole('tooltip')).toHaveText('减少缓存占用，可能重复下载');
  await page.keyboard.press('Escape');
  await label.focus();
  await expect(page.getByRole('tooltip')).toHaveText('减少缓存占用，可能重复下载');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await expect(auto).toBeChecked();
  const hint=group.locator('..').locator('.fui-Field__hint');
  expect((await hint.boundingBox())!.y-((await group.boundingBox())!.y+(await group.boundingBox())!.height)).toBeLessThanOrEqual(4);
  await expect(page.getByText('自动：不保留视频时开启。当前关闭')).toBeVisible();
  await navigateSettings(page,'存储');
  await page.getByRole('radio', {name:'不保留', exact:true}).check();
  await saveSettings(page,'待重启');
  await navigateSettings(page,'下载与缓存');
  await expect(page.getByText('自动：不保留视频时开启。当前开启')).toBeVisible();
  await off.check();
  await expect(page.getByText('可能导致大量缓存未及时回收',{exact:true})).toBeVisible();
  await navigateSettings(page,'存储');
  await page.getByRole('radio', {name:'限制为', exact:true}).check();
  await saveSettings(page,'待重启');
  await navigateSettings(page,'下载与缓存');
  await expect(off).toBeChecked();
  await on.check();
  await expect(page.getByText('可能导致没有完整的视频保存到本地',{exact:true})).toBeVisible();
  await navigateSettings(page,'存储');
  await page.getByRole('radio', {name:'不限制', exact:true}).check();
  await saveSettings(page,'已生效');
  await navigateSettings(page,'下载与缓存');
  await expect(on).toBeChecked();
  await navigate(page, '曲库');
  await navigateSettings(page,'下载与缓存');
  await expect(on).toBeChecked();
  await save.click();
  await expect(save).toBeDisabled();
  expect(api.state.settings.aggressiveBlockReclamation).toBe('on');
  expect(api.state.activeSettings.aggressiveBlockReclamation).toBe('auto');
  await page.reload();
  await expect(on).toBeChecked();
  await off.check();
  await page.getByRole('button', {name:'放弃更改', exact:true}).click();
  await expect(on).toBeChecked();
  await off.check();
  await save.click();
  await expect(save).toBeDisabled();
  await page.reload();
  await expect(off).toBeChecked();
  await auto.check();
  await navigateSettings(page,'存储');
  await page.getByRole('radio', {name:'不保留', exact:true}).check();
  await saveSettings(page,'待重启');
  await navigateSettings(page,'下载与缓存');
  await save.click();
  await expect(save).toBeDisabled();
  expect(api.state.settings.aggressiveBlockReclamation).toBe('auto');
  await page.reload();
  await expect(auto).toBeChecked();
  await expect(page.getByText('自动：不保留视频时开启。当前开启')).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({colorScheme:'dark'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('group', {name:'缓存', exact:true}).screenshot({path:info.outputPath('reclamation-settings.png'),animations:'disabled'});
});
