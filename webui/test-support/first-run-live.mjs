// Production Console from an empty directory; no mocked HTTP responses.
import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
const [base,output]=process.argv.slice(2);
await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:process.env.CI?'chromium':'msedge'});
try {
  const page=await browser.newPage({viewport:{width:1280,height:950}}),errors=[],mutations=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.method()==='POST')mutations.push(new URL(r.url()).pathname);});
  await page.goto(base);
  const dialog=page.getByRole('alertdialog',{name:'使用条款'});
  await expect(dialog).toBeVisible();
  const initialStatus=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/status'&&r.ok());
  await dialog.getByRole('button',{name:'同意完整条款'}).click();
  const status=await (await initialStatus).json();
  expect(status.storageError).toBeUndefined();
  expect(status.restartRequired).toBe(false);
  expect(status.activeSettings.databasePath).toBe(status.defaultDatabasePath);
  expect(status.activeSettings.videoDir).toBe(status.defaultVideoDir);
  await expect(dialog).toHaveCount(0);
  await expect(page.getByText('后台程序：已连接',{exact:true})).toBeVisible();
  await page.screenshot({path:join(output,'first-open.png'),fullPage:true});
  const songs=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/library');
  await page.getByRole('link',{name:'曲库',exact:true}).click();
  expect((await songs).status()).toBe(200);
  await expect(page.getByText('后台程序：已连接',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'历史',exact:true}).click();
  await expect(page.getByText('后台程序：已连接',{exact:true})).toBeVisible();
  await page.goto(base+'/#storage-settings');
  await expect(page.getByRole('textbox',{name:'数据库文件',exact:true})).toHaveValue(status.defaultDatabasePath);
  await expect(page.getByRole('textbox',{name:'完整视频目录',exact:true})).toHaveValue(status.defaultVideoDir);
  await expect(page.getByRole('button',{name:'重启并应用',exact:true})).toBeDisabled();
  await page.goto(base+'/#/help');
  await expect(page.getByText(status.defaultDatabasePath,{exact:true})).toBeVisible();
  await expect(page.getByText(status.defaultVideoDir,{exact:true})).toBeVisible();
  const details=page.locator('#help-paths');
  await expect(details.locator('dt').filter({hasText:'辅助状态'}).locator('+ dd')).toHaveText(/data[\\/]state$/);
  await expect(details.locator('dt').filter({hasText:'临时工作目录'}).locator('+ dd')).not.toBeEmpty();
  await expect(page.getByText(/精简备份可排除 data\/state/)).toBeVisible();
  await page.screenshot({path:join(output,'paths-and-backup.png'),fullPage:true});
  await page.goto(base+'/#/home');
  await page.getByRole('button',{name:'开始加速',exact:true}).click();
  await expect(page.getByText('视频加速已开启。',{exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:850});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:join(output,'first-acceleration.png'),fullPage:true});
  expect(mutations).not.toContain('/api/settings');
  expect(mutations.some(p=>p.startsWith('/api/storage/'))).toBe(false);
  expect(errors).toEqual([]);
  await writeFile(join(output,'result.json'),JSON.stringify({passed:true,mutations,errors},null,2));
  console.log('Fresh application: consent, library, history, default settings and acceleration passed without storage setup or restart.');
} finally {await browser.close();}
